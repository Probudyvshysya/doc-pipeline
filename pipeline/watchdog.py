# -*- coding: utf-8 -*-
"""
СТОРОЖ КОНВЕЙЕРА: отличает «данных нет» от «сбор сломался».

Зачем. Автоматика ломается тихо. Однажды ежедневный сбор встал на пять суток,
и никто не узнал: расписание отрабатывало, скрипт стартовал, лог писался —
просто на выходе не было данных. Молчание системы выглядит ровно как «всё
в порядке», и это худший из возможных отказов.

Две ошибки, на которых сторож переписывался, и обе стоят того, чтобы помнить:

1. **Свежесть мерилась по mtime базы.** Базу трогают и другие процессы, поэтому
   она «выглядела свежей», пока данные в ней устаревали. Предупреждение
   опоздало на трое суток. Теперь свежесть — это отдельная метка, которую
   пишет ТОЛЬКО успешно завершившийся сетевой проход.

2. **Сторож кричал вхолостую.** Он слал тревогу дважды в день при работающем
   конвейере, потому что проверял доставку, а канал доставки был сломан
   отдельно от сбора. Тревога, которая приходит постоянно, перестаёт читаться
   через неделю. Теперь состояний три, и каждое требует разных действий.

Состояния:
    ЗЕЛЁНЫЙ  — прогон был в пределах допустимого окна, данные свежие;
    ЖЁЛТЫЙ   — прогон был, но данных на выходе ноль (источник пуст — это
               не поломка, а факт, который надо знать);
    КРАСНЫЙ  — успешного прогона не было дольше окна: конвейер сломан.
"""
import io
import os
import time

from . import config as C

OKNO_CHASOV = 26          # сутки плюс запас на сдвиг расписания


def otmetit_uspeh(naydeno=0):
    """Вызывать ТОЛЬКО после успешного прохода, а не в начале и не при ошибке."""
    os.makedirs(os.path.dirname(C.STAMP), exist_ok=True)
    io.open(C.STAMP, "w", encoding="utf-8").write("%d %d" % (int(time.time()), naydeno))


def sostoyanie():
    """Возвращает (цвет, сообщение, часов_с_последнего_прогона)."""
    if not os.path.exists(C.STAMP):
        return "КРАСНЫЙ", "успешных прогонов не было ни разу", None
    try:
        syroe = io.open(C.STAMP, encoding="utf-8").read().split()
        kogda, skolko = int(syroe[0]), int(syroe[1] if len(syroe) > 1 else 0)
    except Exception:
        return "КРАСНЫЙ", "метка последнего прогона повреждена", None

    chasov = (time.time() - kogda) / 3600.0
    if chasov > OKNO_CHASOV:
        return ("КРАСНЫЙ",
                "последний успешный прогон %.1f ч назад — конвейер стоит" % chasov,
                chasov)
    if skolko == 0:
        return ("ЖЁЛТЫЙ",
                "прогон прошёл %.1f ч назад, но данных на выходе ноль" % chasov,
                chasov)
    return ("ЗЕЛЁНЫЙ",
            "прогон %.1f ч назад, обработано документов: %d" % (chasov, skolko),
            chasov)


def main():
    cvet, soobshchenie, _ = sostoyanie()
    print("%s: %s" % (cvet, soobshchenie))
    return 0 if cvet == "ЗЕЛЁНЫЙ" else (1 if cvet == "ЖЁЛТЫЙ" else 2)


if __name__ == "__main__":
    raise SystemExit(main())
